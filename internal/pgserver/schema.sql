CREATE TABLE IF NOT EXISTS battery_samples (
  id BIGINT PRIMARY KEY, vehicle_id BIGINT REFERENCES vehicles(id) ON DELETE CASCADE,
  "timestamp" TEXT, battery_level BIGINT, battery_range_km REAL,
