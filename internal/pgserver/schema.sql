CREATE OR REPLACE FUNCTION teslalog_advance_geofence_id() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  PERFORM setval(pg_get_serial_sequence('geofences','id'),
    GREATEST(NEW.id, COALESCE((SELECT MAX(id) FROM geofences),1)), true);
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS teslalog_geofence_id_sequence ON geofences;
CREATE TRIGGER teslalog_geofence_id_sequence AFTER INSERT ON geofences
FOR EACH ROW EXECUTE FUNCTION teslalog_advance_geofence_id();

