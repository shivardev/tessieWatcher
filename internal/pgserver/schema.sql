CREATE TABLE IF NOT EXISTS vehicles (
  id BIGINT PRIMARY KEY, vin TEXT UNIQUE, tesla_id TEXT, display_name TEXT,
  model TEXT, trim_badging TEXT, marketing_name TEXT, exterior_color TEXT,
  wheel_type TEXT, spoiler_type TEXT, efficiency_wh_km REAL,
  created_at TEXT, firmware_version TEXT
);
CREATE TABLE IF NOT EXISTS geofences (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT UNIQUE,
  latitude REAL, longitude REAL, radius_m REAL,
  billing_type TEXT DEFAULT 'per_kwh', cost_per_unit REAL, session_fee REAL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS geocode_cache (
  lat_key REAL NOT NULL, lng_key REAL NOT NULL, name TEXT, created_at TEXT,
  road TEXT, city TEXT, county TEXT, state TEXT, postcode TEXT, country TEXT,
  PRIMARY KEY (lat_key,lng_key)
);
CREATE TABLE IF NOT EXISTS states (
  id BIGINT PRIMARY KEY, vehicle_id BIGINT REFERENCES vehicles(id) ON DELETE CASCADE,
  state TEXT, started_at TEXT, ended_at TEXT
);
CREATE TABLE IF NOT EXISTS drives (
  id BIGINT PRIMARY KEY, vehicle_id BIGINT REFERENCES vehicles(id) ON DELETE CASCADE,
  start_time TEXT, end_time TEXT, start_odometer_km REAL, end_odometer_km REAL,
  distance_km REAL, duration_min REAL, start_battery_level BIGINT, end_battery_level BIGINT,
  start_range_km REAL, end_range_km REAL, start_ideal_range_km REAL, end_ideal_range_km REAL,
  start_lat REAL, start_lng REAL, end_lat REAL, end_lng REAL, max_speed_kmh REAL,
  max_power_kw REAL, min_power_kw REAL, outside_temp_avg_c REAL, inside_temp_avg_c REAL,
  ascent_m REAL, descent_m REAL, status TEXT DEFAULT 'open', start_location TEXT, end_location TEXT
);
CREATE TABLE IF NOT EXISTS positions (
  id BIGINT PRIMARY KEY, drive_id BIGINT REFERENCES drives(id) ON DELETE CASCADE,
  vehicle_id BIGINT REFERENCES vehicles(id) ON DELETE CASCADE, "timestamp" TEXT,
  latitude REAL, longitude REAL, speed_kmh REAL, heading REAL, elevation_m REAL,
  power_kw REAL, odometer_km REAL, battery_level BIGINT, usable_battery_level BIGINT,
  range_km REAL, ideal_range_km REAL, est_range_km REAL, battery_heater_on BIGINT,
  outside_temp_c REAL, inside_temp_c REAL, fan_status BIGINT, driver_temp_setting_c REAL,
  passenger_temp_setting_c REAL, is_climate_on BIGINT, is_rear_defroster_on BIGINT,
  is_front_defroster_on BIGINT, tpms_pressure_fl REAL, tpms_pressure_fr REAL,
  tpms_pressure_rl REAL, tpms_pressure_rr REAL, shift_state TEXT, sentry_mode BIGINT,
  is_user_present BIGINT, valet_mode BIGINT, climate_keeper_mode TEXT,
  battery_heater BIGINT, battery_heater_no_power BIGINT
);
CREATE TABLE IF NOT EXISTS charging_sessions (
  id BIGINT PRIMARY KEY, vehicle_id BIGINT REFERENCES vehicles(id) ON DELETE CASCADE,
  geofence_id BIGINT REFERENCES geofences(id) ON DELETE SET NULL,
  start_time TEXT, end_time TEXT, start_battery_level BIGINT, end_battery_level BIGINT,
  start_range_km REAL, end_range_km REAL, start_ideal_range_km REAL, end_ideal_range_km REAL,
  charge_energy_added_kwh REAL, charge_energy_used_kwh REAL, max_charger_power_kw REAL,
  outside_temp_avg_c REAL, cost REAL, latitude REAL, longitude REAL,
  status TEXT DEFAULT 'open', location TEXT, is_dc_fast_charge BIGINT
);
ALTER TABLE charging_sessions ADD COLUMN IF NOT EXISTS geofence_id BIGINT REFERENCES geofences(id) ON DELETE SET NULL;
CREATE TABLE IF NOT EXISTS charging_samples (
  id BIGINT PRIMARY KEY, charging_session_id BIGINT REFERENCES charging_sessions(id) ON DELETE CASCADE,
  vehicle_id BIGINT REFERENCES vehicles(id) ON DELETE CASCADE, "timestamp" TEXT,
  battery_level BIGINT, usable_battery_level BIGINT, charger_power_kw REAL,
  charger_voltage REAL, charger_actual_current REAL, charger_pilot_current BIGINT,
  charger_phases BIGINT, conn_charge_cable TEXT, fast_charger_present BIGINT,
  fast_charger_brand TEXT, fast_charger_type TEXT, charge_energy_added_kwh REAL,
  range_km REAL, ideal_range_km REAL, battery_heater_on BIGINT,
  not_enough_power_to_heat BIGINT, outside_temp_c REAL, charge_limit_soc BIGINT
