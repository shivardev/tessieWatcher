CREATE OR REPLACE FUNCTION julianday(value TEXT) RETURNS DOUBLE PRECISION
LANGUAGE SQL IMMUTABLE PARALLEL SAFE AS $$
  SELECT EXTRACT(EPOCH FROM value::timestamptz) / 86400.0 + 2440587.5
$$;
CREATE OR REPLACE FUNCTION datetime(value TEXT, modifier TEXT DEFAULT NULL) RETURNS TEXT
LANGUAGE plpgsql STABLE AS $$
DECLARE result timestamptz;
BEGIN
  result := CASE WHEN lower(value) = 'now' THEN now() ELSE value::timestamptz END;
  IF modifier IS NOT NULL THEN result := result + modifier::interval; END IF;
  RETURN to_char(result AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS');
END $$;
CREATE OR REPLACE FUNCTION strftime(format TEXT, value TEXT) RETURNS TEXT
LANGUAGE SQL STABLE AS $$
  SELECT to_char(value::timestamptz AT TIME ZONE 'UTC',
    CASE format WHEN '%Y-%m-%dT%H:00:00Z' THEN 'YYYY-MM-DD"T"HH24:00:00"Z"'
                WHEN '%Y-%m-%d' THEN 'YYYY-MM-DD'
                WHEN '%Y-%m' THEN 'YYYY-MM'
                WHEN '%H' THEN 'HH24'
                ELSE 'YYYY-MM-DD HH24:MI:SS' END)
$$;
CREATE OR REPLACE FUNCTION printf(format TEXT, a DOUBLE PRECISION, b DOUBLE PRECISION) RETURNS TEXT
LANGUAGE SQL IMMUTABLE PARALLEL SAFE AS $$ SELECT to_char(a,'FM999999990.0000') || ', ' || to_char(b,'FM999999990.0000') $$;
CREATE OR REPLACE FUNCTION round(value DOUBLE PRECISION, digits INTEGER) RETURNS NUMERIC
LANGUAGE SQL IMMUTABLE PARALLEL SAFE AS $$ SELECT pg_catalog.round(value::numeric,digits) $$;
CREATE OR REPLACE FUNCTION max(a DOUBLE PRECISION,b DOUBLE PRECISION) RETURNS DOUBLE PRECISION
LANGUAGE SQL IMMUTABLE PARALLEL SAFE AS $$ SELECT greatest(a,b) $$;
CREATE OR REPLACE FUNCTION min(a DOUBLE PRECISION,b DOUBLE PRECISION) RETURNS DOUBLE PRECISION
LANGUAGE SQL IMMUTABLE PARALLEL SAFE AS $$ SELECT least(a,b) $$;
